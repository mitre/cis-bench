#!/usr/bin/env python3
"""Generate the XCCDF model packages from the XCCDF schemas, or check the committed ones.

    python scripts/generate_xccdf_models.py           # write the packages
    python scripts/generate_xccdf_models.py --check   # exit 1 if the packages differ

The models are generated by xsdata (`xsdata generate`, the dev extra) with the project's
.xsdata.xml, then ruff sorts the imports and formats them with the project's settings. Nothing
in the generated files is edited by hand or by this script.

Inputs, the schema copies in src/cis_bench/schemas/:
    xccdf-1.1.4.xsd -> cis_bench.models.xccdf_v1_1 (it also reads cpe-1.0.xsd,
                       platform-0.2.3.xsd and xccdfp-1.1.xsd from the same folder)
    xccdf_1.2.xsd   -> cis_bench.models.xccdf
These are not the schemas `cis-bench validate` checks documents with (xccdf/1.1/ and
xccdf/1.2/ in the same folder); they are the copies the committed models were first made from.
Generating reads xml.xsd from http://www.w3.org and dc.xsd from dublincore.org, so it needs
the network. The copies also name CPE schemas at /schema/cpe/... paths that do not exist;
xsdata warns about those and generates the fields that use them as plain strings.

xsdata writes into the folder it runs in, so the packages are generated in a temporary folder
and only the model package files are compared or copied into src/. Generating replaces every
module in a model package and removes modules the generator no longer writes.
"""

import argparse
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = Path(".xsdata.xml")
SOURCE_FOLDER = Path("src")


@dataclass(frozen=True)
class Model:
    """A schema (relative to the project root) and the package its models are generated into."""

    schema: Path
    package: str


MODELS: tuple[Model, ...] = (
    Model(
        schema=Path("src/cis_bench/schemas/xccdf-1.1.4.xsd"), package="cis_bench.models.xccdf_v1_1"
    ),
    Model(schema=Path("src/cis_bench/schemas/xccdf_1.2.xsd"), package="cis_bench.models.xccdf"),
)


class GenerationError(Exception):
    """xsdata or ruff could not produce a model package; nothing was written."""


def package_folder(root: Path, package: str) -> Path:
    """Where a package's modules live in the project."""
    return root / SOURCE_FOLDER / Path(*package.split("."))


def _run(
    command: list[str], cwd: Path, stdin: str | None = None
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        command,
        input=stdin,
        capture_output=True,
        text=True,
        cwd=cwd,
        check=False,
    )


def _generate(model: Model, root: Path, workdir: Path) -> dict[str, str]:
    """Run xsdata for one schema in workdir; return the package's modules by file name.

    xsdata exits 0 with only a warning when it cannot read a schema, so a run that writes no
    module is the error.
    """
    result = _run(
        [
            sys.executable,
            "-m",
            "xsdata",
            "generate",
            str(root / model.schema),
            "--config",
            str(root / CONFIG),
            "--package",
            model.package,
        ],
        cwd=workdir,
    )
    output = workdir / Path(*model.package.split("."))
    modules = {path.name: path.read_text(encoding="utf-8") for path in sorted(output.glob("*.py"))}
    if result.returncode != 0 or not modules:
        raise GenerationError(
            f"{model.schema}: xsdata generated no modules\n{result.stdout}{result.stderr}"
        )
    return modules


def _format(text: str, path: Path, root: Path) -> str:
    """Sort imports and format one module with the project's ruff settings.

    ruff reads the source from stdin as if it were at `path`, so the project's per-file
    settings for that path apply. A finding ruff cannot fix is an error.
    """
    relative = path.relative_to(root)
    ruff = [sys.executable, "-m", "ruff"]
    fixed = _run([*ruff, "check", "--fix", "--stdin-filename", str(relative), "-"], root, text)
    if fixed.returncode != 0:
        raise GenerationError(f"{relative}: ruff check\n{fixed.stdout}{fixed.stderr}")
    formatted = _run([*ruff, "format", "--stdin-filename", str(relative), "-"], root, fixed.stdout)
    if formatted.returncode != 0:
        raise GenerationError(f"{relative}: ruff format\n{formatted.stderr}")
    return formatted.stdout


def render(model: Model, root: Path) -> dict[Path, str]:
    """Generate and format one model package; return each module by its project path.

    Nothing in the project is written.
    """
    with tempfile.TemporaryDirectory(prefix="xccdf-models-") as workdir:
        modules = _generate(model, root, Path(workdir))
    folder = package_folder(root, model.package)
    return {folder / name: _format(text, folder / name, root) for name, text in modules.items()}


def committed(model: Model, root: Path) -> dict[Path, str]:
    """The model package's modules as they are in the project."""
    folder = package_folder(root, model.package)
    return {path: path.read_text(encoding="utf-8") for path in sorted(folder.glob("*.py"))}


def differences(rendered: dict[Path, str], current: dict[Path, str], root: Path) -> list[str]:
    """One line per module that is changed, missing from the project, or not generated."""
    lines = []
    for path in sorted(set(rendered) | set(current)):
        relative = path.relative_to(root).as_posix()
        if path not in current:
            lines.append(f"missing: {relative}")
        elif path not in rendered:
            lines.append(f"not generated: {relative}")
        elif rendered[path] != current[path]:
            lines.append(f"differs: {relative}")
    return lines


def write(rendered: dict[Path, str], current: dict[Path, str]) -> None:
    """Write the generated modules and remove the package's modules that were not generated."""
    for path in sorted(set(current) - set(rendered)):
        path.unlink()
    for path, text in rendered.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def main(
    argv: list[str] | None = None, root: Path = ROOT, models: tuple[Model, ...] = MODELS
) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="report whether the committed packages match what the generator writes; write nothing",
    )
    args = parser.parse_args(argv)

    try:
        rendered = {model: render(model, root) for model in models}
    except GenerationError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if args.check:
        lines = [
            line
            for model in models
            for line in differences(rendered[model], committed(model, root), root)
        ]
        for line in lines:
            print(line)
        if lines:
            print("The committed models do not match; run scripts/generate_xccdf_models.py.")
            return 1
        print("The committed models match the generator's output.")
        return 0

    for model in models:
        write(rendered[model], committed(model, root))
        print(f"generated {model.package} from {model.schema.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
